#!/usr/bin/env node
/**
 * Pre-render every graphviz visual block in domains.ts to a static SVG
 * string. Output: website/lib/graphviz-cache.ts
 *
 * Why: dev/prod webpack consistently fails to chunk-load @viz-js/viz on
 * the client. Running viz once at script time and shipping the SVG string
 * eliminates the runtime dependency entirely.
 *
 * Run:  node scripts/prerender_graphviz.mjs
 * Re-run whenever a domain task gets a new `kind: "graphviz"` visual.
 */

import { instance } from "@viz-js/viz";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";
import { build } from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WEBSITE = resolve(__dirname, "..");
const DOMAINS_TS = resolve(WEBSITE, "lib/domains.ts");
const OUT = resolve(WEBSITE, "lib/graphviz-cache.ts");

async function loadDomains() {
  // Bundle domains.ts → CommonJS so we can require() it from a node script.
  // External-marks every other module so we only get this single file.
  const result = await build({
    entryPoints: [DOMAINS_TS],
    bundle: false,
    format: "cjs",
    platform: "node",
    target: "node18",
    write: false,
    loader: { ".ts": "ts" },
  });
  const code = result.outputFiles[0].text;
  // Strip the type-only import (esbuild keeps the line because we asked it
  // not to bundle external modules; we just remove the require call).
  const stripped = code.replace(
    /(?:const|var)\s+\w+\s*=\s*require\(['"]\.\/types['"]\);?/,
    "",
  );
  // Eval into a sandbox-ish module scope.
  const mod = { exports: {} };
  const fn = new Function("module", "exports", stripped);
  fn(mod, mod.exports);
  // @ts-ignore
  return mod.exports.DOMAINS;
}

function escapeForTs(s) {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

async function main() {
  console.log("Loading viz-js...");
  const viz = await instance();
  console.log("Loading domains.ts...");
  const DOMAINS = await loadDomains();

  if (!DOMAINS) {
    throw new Error("Could not load DOMAINS — esbuild output is empty.");
  }

  const cache = {};
  let count = 0;
  let failures = 0;

  for (const d of DOMAINS) {
    for (const t of d.tasks ?? []) {
      const visuals = t.deepDive?.visuals ?? [];
      for (let i = 0; i < visuals.length; i++) {
        const v = visuals[i];
        if (v.kind !== "graphviz") continue;
        const key = `${t.id}::${i}`;
        try {
          const svg = viz.renderString(v.dot, { format: "svg" });
          // Strip the XML declaration if present
          cache[key] = svg.replace(/^<\?xml[^>]+\?>\s*/, "");
          count++;
          process.stdout.write(`  ✓ ${key}\n`);
        } catch (e) {
          failures++;
          console.error(`  ✗ ${key}: ${e.message}`);
        }
      }
    }
  }

  // Build TypeScript output
  const lines = [
    "// AUTO-GENERATED by scripts/prerender_graphviz.mjs — do not edit by hand.",
    "// Re-run when a `deepDive.visuals` graphviz block changes.",
    "",
    "export const GRAPHVIZ_CACHE: Record<string, string> = {",
  ];
  for (const [key, svg] of Object.entries(cache)) {
    lines.push(`  ${JSON.stringify(key)}: \`${escapeForTs(svg)}\`,`);
  }
  lines.push("};");
  lines.push("");
  lines.push("/** Look up by `${taskId}::${visualIndex}` — returns undefined if not pre-rendered. */");
  lines.push("export function getCachedGraphviz(taskId: string, idx: number): string | undefined {");
  lines.push("  return GRAPHVIZ_CACHE[`${taskId}::${idx}`];");
  lines.push("}");
  lines.push("");

  await writeFile(OUT, lines.join("\n"));
  console.log(`\nWrote ${OUT}`);
  console.log(`Pre-rendered ${count} diagrams (${failures} failed)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

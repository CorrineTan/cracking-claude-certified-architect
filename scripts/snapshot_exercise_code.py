#!/usr/bin/env python3
"""Snapshot the exercise source files into website/lib/exercise-code.ts.

For each completed exercise, we extract the key files referenced by the
README + step list, then bundle them as a TypeScript object so the website
can render the actual code under each step without needing fs at runtime.

Run:  python3 scripts/snapshot_exercise_code.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
EX_ROOT = REPO_ROOT / "Exercise"
OUTPUT = REPO_ROOT / "website" / "lib" / "exercise-code.ts"

# Per-exercise file selection. Order = display order under "Source files".
SELECTION = {
    "multi-tool-escalation": {
        "root": "Exercise1_Multi_Tool_Escalaction_Logic",
        "files": [
            "main.py",
            "src/agent.py",
            "src/hooks.py",
            "src/mcp_server.py",
            "src/mcp_client.py",
            "src/context.py",
            "src/mock_data.py",
            ".mcp.json",
        ],
        # Step 0..N → list of file paths (relative to exercise root)
        "step_files": [
            ["src/mcp_server.py", "src/mcp_client.py"],
            ["src/agent.py"],
            ["src/mcp_server.py"],
            ["src/hooks.py", "src/agent.py"],
            ["src/agent.py", "src/context.py"],
        ],
    },
    "team-workflow": {
        "root": "Exercise2_Claude_Code_Team_Workflow",
        "files": [
            "CLAUDE.md",
            ".mcp.json",
            ".claude/rules/api-conventions.md",
            ".claude/rules/testing.md",
            ".claude/rules/frontend-conventions.md",
            ".claude/commands/code-review.md",
            ".claude/skills/analyze-module/SKILL.md",
            "src/api/routes/__init__.py",
            "src/models/order.py",
            "src/frontend/components/OrderStatus.tsx",
            "tests/api/test_orders.py",
        ],
        "step_files": [
            ["CLAUDE.md"],
            [
                ".claude/rules/api-conventions.md",
                ".claude/rules/testing.md",
                ".claude/rules/frontend-conventions.md",
            ],
            [".claude/skills/analyze-module/SKILL.md", ".claude/commands/code-review.md"],
            [".mcp.json"],
            ["CLAUDE.md", "src/api/routes/__init__.py"],
        ],
    },
}


def extension(path: str) -> str:
    if path.endswith(".tsx"):
        return "tsx"
    if path.endswith(".ts"):
        return "ts"
    if path.endswith(".py"):
        return "python"
    if path.endswith(".json"):
        return "json"
    if path.endswith(".md"):
        return "markdown"
    if path.endswith(".sh"):
        return "bash"
    return "text"


def ts_string(s: str) -> str:
    return (
        '"'
        + s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
        .replace("`", "\\u0060")
        + '"'
    )


def main() -> None:
    output = {}
    for slug, sel in SELECTION.items():
        ex_root = EX_ROOT / sel["root"]
        if not ex_root.exists():
            print(f"WARN: {ex_root} missing — skipping {slug}")
            continue
        files = []
        for rel in sel["files"]:
            p = ex_root / rel
            if not p.exists():
                print(f"  - skip (missing) {rel}")
                continue
            try:
                content = p.read_text()
            except Exception as e:
                print(f"  - skip (read err) {rel}: {e}")
                continue
            files.append(
                {
                    "path": rel,
                    "language": extension(rel),
                    "content": content,
                    "lineCount": content.count("\n") + 1,
                    "byteSize": len(content.encode("utf-8")),
                }
            )
        output[slug] = {
            "exerciseRoot": sel["root"],
            "files": files,
            "stepFiles": sel["step_files"],
        }
        print(f"{slug}: {len(files)} files snapshotted")

    # Emit as TS
    lines = [
        "// AUTO-GENERATED by scripts/snapshot_exercise_code.py — do not edit by hand.",
        "// Snapshots key source files from the Exercise/ folders so the website",
        "// can render real code under each step without filesystem access.",
        "",
        "export interface ExerciseFile {",
        "  path: string;",
        "  language: string;",
        "  content: string;",
        "  lineCount: number;",
        "  byteSize: number;",
        "}",
        "",
        "export interface ExerciseCode {",
        "  exerciseRoot: string;",
        "  files: ExerciseFile[];",
        "  /** Per step (by index) → list of file paths to highlight. */",
        "  stepFiles: string[][];",
        "}",
        "",
        "export const EXERCISE_CODE: Record<string, ExerciseCode> = {",
    ]
    for slug, payload in output.items():
        lines.append(f"  {ts_string(slug)}: {{")
        lines.append(f"    exerciseRoot: {ts_string(payload['exerciseRoot'])},")
        lines.append("    files: [")
        for f in payload["files"]:
            lines.append("      {")
            lines.append(f"        path: {ts_string(f['path'])},")
            lines.append(f"        language: {ts_string(f['language'])},")
            lines.append(f"        content: {ts_string(f['content'])},")
            lines.append(f"        lineCount: {f['lineCount']},")
            lines.append(f"        byteSize: {f['byteSize']},")
            lines.append("      },")
        lines.append("    ],")
        lines.append("    stepFiles: [")
        for paths in payload["stepFiles"]:
            arr = ", ".join(ts_string(p) for p in paths)
            lines.append(f"      [{arr}],")
        lines.append("    ],")
        lines.append("  },")
    lines.append("};")
    lines.append("")

    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
